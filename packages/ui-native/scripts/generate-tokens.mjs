import { formatHex, formatRgb, parse, toGamut } from 'culori';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/**
 * Generates `src/tokens.ts` from `@bpagoaga/ui/theme.css`, the design system's single
 * source of truth, converted to what React Native understands:
 *   - OKLCH colours → hex (shadows → rgba), as React Native has no OKLCH support;
 *   - rem → dp (1rem = 16), em letter-spacing and unitless line-heights → dp;
 *   - semantic aliases (`var(--color-neutral-10)`) → their resolved value.
 *
 * `--check` fails instead of writing when the committed file is out of date (lint / CI).
 */
const THEME = fileURLToPath(import.meta.resolve('@bpagoaga/ui/theme.css'));
const OUTPUT = fileURLToPath(new URL('../src/tokens.ts', import.meta.url));
const REM = 16;

const declarations = new Map(
  [...readFileSync(THEME, 'utf8').matchAll(/^\s*--([\w-]+):\s*([^;]+);/gm)].map(([, name, value]) => [
    name,
    value.trim(),
  ]),
);

const resolve = (value) => value.replace(/var\(--([\w-]+)\)/g, (_, name) => resolve(declarations.get(name)));
const round = (value) => Math.round(value * 100) / 100;
const toDp = (value) => round(parseFloat(value) * (value.endsWith('rem') ? REM : 1));
// Gamut-mapped in OKLCH (keeps the hue) rather than clipped per RGB channel.
const toSrgb = toGamut('rgb', 'oklch');
const toHex = (value) => formatHex(toSrgb(parse(value)));
// CSS colour functions inside a longer value (box-shadow): oklch(20% 0.02 260 / 0.06) → rgba(…).
const colorsToRgb = (value) => value.replace(/oklch\([^)]*\)/g, (color) => formatRgb(toSrgb(parse(color))));

/** `prefix-name` tokens, without their sub-properties (`--text-title-l--line-height`). */
const tokens = (prefix) =>
  [...declarations]
    .filter(([name]) => name.startsWith(`${prefix}-`) && !name.includes('--') && !name.endsWith('*'))
    .map(([name, value]) => [name.slice(prefix.length + 1), resolve(value)]);

const colors = Object.fromEntries(tokens('color').map(([name, value]) => [name, toHex(value)]));

const typography = Object.fromEntries(
  tokens('text').map(([name, value]) => {
    const fontSize = toDp(value);
    const sub = (key) => declarations.get(`text-${name}--${key}`);
    const lineHeight = sub('line-height');
    const letterSpacing = sub('letter-spacing');
    return [
      name,
      {
        fontSize,
        lineHeight: lineHeight.endsWith('rem') ? toDp(lineHeight) : round(parseFloat(lineHeight) * fontSize),
        letterSpacing: letterSpacing ? round(parseFloat(letterSpacing) * fontSize) : 0,
        fontWeight: sub('font-weight') ?? '400',
      },
    ];
  }),
);

const radii = Object.fromEntries(tokens('radius').map(([name, value]) => [name, toDp(value)]));
const shadows = Object.fromEntries(tokens('shadow').map(([name, value]) => [name, colorsToRgb(value)]));

const output = `// Generated by scripts/generate-tokens.mjs from @bpagoaga/ui/src/theme.css — do not edit.
// Run \`pnpm --filter @bpagoaga/ui-native tokens\` after changing the design tokens.

export const colors = ${JSON.stringify(colors, null, 2)} as const;

export const typography = ${JSON.stringify(typography, null, 2)} as const;

export const radii = ${JSON.stringify(radii, null, 2)} as const;

/** CSS \`box-shadow\` strings, supported by React Native's \`boxShadow\` style (New Architecture). */
export const shadows = ${JSON.stringify(shadows, null, 2)} as const;
`;

if (process.argv.includes('--check')) {
  if (readFileSync(OUTPUT, 'utf8') !== output) {
    console.error('src/tokens.ts is out of date: run `pnpm --filter @bpagoaga/ui-native tokens`.');
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, output);
}
